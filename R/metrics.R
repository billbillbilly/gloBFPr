#' @description
#' `get_morphology`: Computes a set of morphological properties and geometric descriptors for each building footprint polygon.
#' These include area, perimeter, surface area, volume, shape compactness, elongation, and accessibility measures.
#'
#' @return
#' `get_morphology` returns an `sf` object identical to input \code{x},
#' with additional columns for:
#' \itemize{
#'  \item \code{g_area}: Ground area of footprint
#'  \item \code{pmeter}: Perimeter length of footprint
#'  \item \code{v_surf}: Vertical surface area (walls)
#'  \item \code{t_surf}: Total surface area (walls + roof)
#'  \item \code{vol}: Volume (area * height)
#'  \item \code{obb_vol}: Volume of oriented bounding box
#'  \item \code{pa_ratio}: Perimeter-area ratio
#'  \item \code{rec}: Rectangular compactness
#'  \item \code{fra}: Fractal dimension ratio
#'  \item \code{cbn}: Cuboidness index
#'  \item \code{hem}: Hemisphericality index
#'  \item \code{cnv}: Convexity index
#'  \item \code{me_dist}: Mean edge accessibility distance
#'  \item \code{mp_dist}: Mean pairwise distance within the footprint
#'  \item \code{vol_exch}: Volume exchange ratio
#'  \item \code{elo_x/elo_y/elo_z}: Elongation ratios (x/y/z axis)
#' }
#'
#' @examples
#' library(gloBFPr)
#' data(globfp_example)
#' globfp_example <- sf::st_as_sfc(globfp_example)
#' result <- gloBFPr::get_morphology(globfp_example[c(1:3),])
#'
#' @export
#' @rdname get_metrics
get_morphology <- function(x = NULL, quiet = FALSE) {
  if (inherits(x, 'NULL')) {
    cli::cli_alert_info("Please input building footprint polygon generated by `search_3dglobdf()`.")
    return(x)
  }
  projected_poly <- x

  old_opt <- getOption("future.globals.maxSize")
  on.exit(options(future.globals.maxSize = old_opt), add = TRUE)
  options(future.globals.maxSize = 3 * 1024^3)

  workers <- as.numeric(future::availableCores())
  # Set future plan depending on OS
  os <- Sys.info()[["sysname"]]
  if (os == "Windows" || isFALSE(parallelly::supportsMulticore())) {
    future::plan(future::multisession, workers = workers - 1)
  } else {
    future::plan(future::multicore, workers = workers - 1)
  }
  on.exit(future::plan(future::sequential), add = TRUE)

  start_time <- Sys.time()

  #--- Properties ---
  cli::cli_alert_info('Start computing geometric properties ...')
  projected_poly$g_area <- as.numeric(sf::st_area(projected_poly))
  projected_poly$pmeter <- as.numeric(lwgeom::st_perimeter(projected_poly))
  projected_poly$v_surf <- projected_poly$pmeter * projected_poly$Height
  projected_poly$t_surf <- projected_poly$v_surf + projected_poly$g_area
  projected_poly$vol <- projected_poly$g_area * projected_poly$Height
  projected_poly$obb_vol <- as.numeric(sf::st_area(sf::st_minimum_rotated_rectangle(projected_poly)) * projected_poly$Height)

  #--- Indices ---
  cli::cli_alert_info('Parallel computing for geometric indices ...')
  projected_poly$pa_ratio <- projected_poly$pmeter / projected_poly$g_area # Perimeter-Area Ratio
  projected_poly$rec <- as.numeric(projected_poly$g_area / sf::st_area(sf::st_minimum_rotated_rectangle(projected_poly)))
  projected_poly$fra <- 1 - log(projected_poly$vol + 1e-9) / (1.5 * log(projected_poly$t_surf + 1e-9))
  projected_poly$cbn <- 6 * (projected_poly$vol^2)^(1/3) / projected_poly$t_surf

  # --- Parallel Loop for Shape Metrics ---
  building_list <- lapply(seq_len(nrow(projected_poly)), function(i) projected_poly[i, ])
  morpho_results <- furrr::future_map(
    building_list,
    function(poly_) {
      list(
        hem = cal_hemisphericality(poly_),
        cnv = cal_convexity(poly_),
        me_dist = cal_accessibility(poly_),
        mp_dist = cal_mean_pairwise_distance(poly_),
        vol_exch = cal_volume_exchange_ratio(poly_),
        elo_ratios = cal_elongation_ratios(poly_)
      )
    },
    .options = furrr::furrr_options(seed = TRUE),
    .progress = TRUE
  )

  # --- Assign results back ---
  projected_poly$hem <- vapply(morpho_results, function(x) x$hem, numeric(1))
  projected_poly$cnv <- vapply(morpho_results, function(x) x$cnv, numeric(1))
  projected_poly$me_dist <- vapply(morpho_results, function(x) x$me_dist, numeric(1))
  projected_poly$mp_dist <- vapply(morpho_results, function(x) x$mp_dist, numeric(1))
  projected_poly$vol_exch <- vapply(morpho_results, function(x) x$vol_exch, numeric(1))
  projected_poly$elo_x <- vapply(morpho_results, function(x) x$elo_ratios[[1]], numeric(1))
  projected_poly$elo_y <- vapply(morpho_results, function(x) x$elo_ratios[[2]], numeric(1))
  projected_poly$elo_z <- vapply(morpho_results, function(x) x$elo_ratios[[3]], numeric(1))

  cli::cli_alert_success('Finished computing morphology metrics')

  end_time <- Sys.time()
  process_time <- as.numeric(difftime(end_time, start_time, units = "secs"))
  time_taken(process_time)

  return(projected_poly)
}

#' @description
#' `get_pop_density`: Downloads and extracts population density data from the GHSL
#' (Global Human Settlement Layer) dataset for a specified year, and assigns
#' population density values to each input building polygon based on its
#' centroid location.
#'
#' @param year numeric. (only required for `get_pop_density`) Year of the GHSL
#' dataset to use. Must be one of: 1975, 1980, 1985, 1990, 1995, 2000, 2005,
#' 2010, 2015, 2020, 2025, or 2030. Default is 2025.
#'
#' @return
#' `get_pop_density` returns an `sf` object identical to input \code{x},
#' with an added column:
#' \itemize{
#'   \item \code{pop_den}: Estimated population density (people per 10000m²)
#'   at the centroid of each building polygon.
#' }
#'
#' @examples
#' result <- gloBFPr::get_pop_density(# globfp_example[c(1:3),],
#'                                    year = 2025)
#'
#'
#' @export
#' @rdname get_metrics
get_pop_density <- function(x = NULL, year = 2025) {
  if (inherits(x, 'NULL')) {
    cli::cli_alert_info("Please input building footprint polygon generated by `search_3dglobdf()`.")
    return(x)
  }

  # Store the original 'timeout' option and ensure it's reset upon function exit
  terra::terraOptions(progress=0)
  on.exit(terra::terraOptions(progress=3), add = TRUE)

  start_time <- Sys.time()

  bbox <- get_bbox(x)
  utm_crs <- get_utm_crs(bbox)
  projected_poly <- sf::st_transform(x, utm_crs)

  # get population map
  r <- get_GHSpop(bbox = bbox, year = year)

  # use all centroids of projected_poly to extract value from the raster
  pop_vals <- suppressWarnings(
    terra::extract(r, terra::vect(sf::st_centroid(projected_poly)),
                   raw = TRUE, ID = FALSE)[, 1]
  )
  # link pop_density_df back to projected_poly
  projected_poly$pop_den <- pop_vals

  cli::cli_alert_success('Finished linking (GHSL) population density to buildings')
  end_time <- Sys.time()
  process_time <- as.numeric(difftime(end_time, start_time, units = "secs"))
  time_taken(process_time)

  return(projected_poly)
}

#' @description
#' `get_residential`: Estimate residential and non-residential building based on
#' Global Human Settlement Layer (GHSL) built-up surface data
#' @param threshold numeric. threshould (%) for decide whether a building is
#' residential or not. For example, if `threshold = 70`, a building, located in
#' a cell with more than 70% is residential building footprint area, is classified
#' as residential.
#' @return
#' `get_residential` returns an `sf` object identical to input \code{x},
#' with additional columns :
#' \code{res}: logical. Whether the building is residential or not.
#'
#' @examples
#' result <- gloBFPr::get_residential(globfp_example[c(1:3),])
#'
#' @export
#' @rdname get_metrics
get_residential <- function(x = NULL, year = NULL, threshold = 80) {
  if (inherits(x, 'NULL')) {
    cli::cli_alert_info("Please input building footprint polygon generated by `search_3dglobdf()`.")
    return(NULL)
  }

  if (inherits(year, 'NULL')) {
    cli::cli_alert_info("Please input year")
    return(NULL)
  }

  terra::terraOptions(progress=0)
  on.exit(terra::terraOptions(progress=3), add = TRUE)

  start_time <- Sys.time()

  bbox <- get_bbox(x)
  utm_crs <- get_utm_crs(bbox)
  projected_poly <- sf::st_transform(x, utm_crs)
  projected_poly$res <- FALSE
  projected_poly$g_area <- as.numeric(sf::st_area(projected_poly$geometry))

  # calculate residential
  r_res <- get_GHSres(bbox = bbox, year = year)

  # use all centroids of projected_poly to extract value from rasters
  res_vals <- suppressWarnings(
    terra::extract(r_res, terra::vect(sf::st_centroid(projected_poly)),
                     raw = TRUE, ID = FALSE)[, 1]
  )
  nres_vals <- suppressWarnings(
    terra::extract(r_nres, terra::vect(sf::st_centroid(projected_poly)),
                   raw = TRUE, ID = FALSE)[, 1]
  )
  # link building surface area back to projected_poly
  projected_poly$res_vals <- res_vals
  projected_poly$res_delta <- projected_poly$res_vals - projected_poly$g_area
  # classify residential building
  projected_poly[projected_poly$res_delta > 0,]$res <- TRUE
  projected_poly[projected_poly$res_vals <= threshold,]$res <- FALSE

  cli::cli_alert_success('Finished estimating residnetial buildings')
  end_time <- Sys.time()
  process_time <- as.numeric(difftime(end_time, start_time, units = "secs"))
  time_taken(process_time)

  # Ensure cleanup
  on.exit(unlink(temp_paths, recursive = TRUE), add = TRUE)
  return(projected_poly)
}

#' @description
#' `get_neighbors`: Computes the number of neighboring buildings and their average and standard
#' deviation of centroid distances, based on a fixed-radius buffer and
#' Voronoi-based adjacency.
#'
#' @param radius numeric. (only required for `get_neighbors`, `get_gbvi`, and
#' `get_dng`)
#' A numeric value specifying the buffer radius (in meters) used to define
#' the proximity of a building footprint centroid. Default for `get_neighbors`, and
#' `get_gbvi` and `get_dng` is respectfully 500 and 800.
#'
#' @return
#' `get_neighbors` returns an `sf` object identical to input \code{x},
#' with additional columns for:
#' \itemize{
#'   \item \code{n_count}: Number of adjacent buildings within the radius.
#'   \item \code{m_ndist}: Mean distance from the building centroid
#'   to neighboring building centroids.
#'   \item \code{sd_ndist}: Standard deviation of those distances.
#' }
#'
#'
#' @examples
#' result <- gloBFPr::get_neighbors(globfp_example[c(1:3),], radius = 100)
#' @importFrom Rcpp evalCpp
#' @export
#' @rdname get_metrics
get_neighbors <- function(x = NULL, radius = 500) {
  if (inherits(x, 'NULL')) {
    cli::cli_alert_info("Please input building footprint polygon generated by `search_3dglobdf()`.")
    return(x)
  }

  old_opt <- getOption("future.globals.maxSize")
  on.exit(options(future.globals.maxSize = old_opt), add = TRUE)
  options(future.globals.maxSize = 3 * 1024^3)

  workers <- as.numeric(future::availableCores())
  # Set future plan depending on OS
  os <- Sys.info()[["sysname"]]
  if (os == "Windows" || isFALSE(parallelly::supportsMulticore())) {
    future::plan(future::multisession, workers = workers - 1)
  } else {
    future::plan(future::multicore, workers = workers - 1)
  }

  start_time <- Sys.time()
  utm_crs <- get_utm_crs(get_bbox(x))
  projected_poly <- sf::st_transform(x, utm_crs)

  # Ensure consistent IDs
  if (!"id" %in% names(projected_poly)) {
    projected_poly$id <- seq_len(nrow(projected_poly))
  }

  # Precompute centroids once
  all_centroids <- suppressWarnings(sf::st_centroid(projected_poly))

  # Prepare a list of per-building input objects
  pb <- utils::txtProgressBar(min = 0, max = nrow(projected_poly), style = 3)
  input_list <- lapply(seq_len(nrow(projected_poly)), function(i) {
    utils::setTxtProgressBar(pb, i)
    list(
      poly = projected_poly[i, ],
      poly_id = projected_poly$id[i],
      all_polys = projected_poly,
      all_centroids = all_centroids,
      radius = radius
    )
  })

  # Parallel computation
  neighbor_results <- furrr::future_map(
    input_list,
    function(b) {
      poly_ <- b$poly
      poly_id <- b$poly_id
      all_polys <- b$all_polys
      all_centroids <- b$all_centroids
      radius <- b$radius

      # Get centroid and buffer
      this_centroid <- suppressWarnings(sf::st_centroid(poly_))
      buffer_zone <- sf::st_buffer(this_centroid, dist = radius)
      buffer_zone <- sf::st_transform(buffer_zone, sf::st_crs(all_polys))

      # Filter neighbors within buffer
      intersected <- sf::st_intersects(all_polys, buffer_zone, sparse = FALSE)[, 1]
      if (sum(intersected) <= 1) {
        return(list(n = 0, m = NA_real_, sd = NA_real_))
      }

      filtered_poly <- all_polys[intersected, ]
      filtered_centroids <- all_centroids[intersected, ]
      centroid_union <- sf::st_union(filtered_centroids)
      voronoi_polygons <- sf::st_voronoi(centroid_union) |>
        sf::st_collection_extract("POLYGON")
      voronoi_sf <- sf::st_sf(geometry = sf::st_sfc(voronoi_polygons),
                              crs = sf::st_crs(filtered_poly))
      voronoi_sf$id <- seq_len(nrow(filtered_poly))

      # Index of current building in filtered set
      idx <- which(filtered_poly$id == poly_id)
      if (length(idx) == 0) {
        return(list(n = 0, m = NA_real_, sd = NA_real_))
      }

      # Find touching polygons
      adjacency <- sf::st_touches(voronoi_sf)
      neighbor_ids <- adjacency[[idx]]
      if (length(neighbor_ids) == 0) {
        return(list(n = 0, m = NA_real_, sd = NA_real_))
      }

      neighbor_centroids <- filtered_centroids[neighbor_ids, ]
      dists <- sf::st_distance(this_centroid, neighbor_centroids)
      mean_dist <- mean(as.numeric(dists))
      sd_dist <- if (length(neighbor_ids) > 1) stats::sd(as.numeric(dists)) else NA_real_

      return(list(n = length(neighbor_ids), m = mean_dist, sd = sd_dist))
    },
    .options = furrr::furrr_options(seed = TRUE),
    .progress = TRUE
  )

  # Combine results back into the main data
  projected_poly$n_count <- vapply(neighbor_results, function(x) x$n, numeric(1))
  projected_poly$m_ndist <- vapply(neighbor_results, function(x) x$m, numeric(1))
  projected_poly$sd_ndist <- vapply(neighbor_results, function(x) x$sd, numeric(1))

  end_time <- Sys.time()
  process_time <- as.numeric(difftime(end_time, start_time, units = "secs"))
  time_taken(process_time)

  return(projected_poly)
}


#' @description
#' `get_bgvi`: Calculate the Building Green View Index (BGVI) for each building volume
#' @param datasource character. The data source for computing greenspace, including:
#' \itemize{
#'  \item \code{metachm}:
#'  \item \code{esri}:
#'  \item \code{dentinel2}:
#' }
#' @param min_tree_height numeric. (only required for `get_bgvi` and `get_dng`)
#' When `datasource = "metachm"`, minimum height threshold (in meters) to classify
#' vegetation as trees in the CHM. Default is 2.
#' @param zoom numeric. (only required for `get_bgvi` and `get_dng`)
#' Zoom level of map tile when `datasource = "esri"` or `datasource = "dentinel2"`.
#' The default is `17`. The higher level of zoom will lead to higher resolution
#' of greenspace data for computing BGVI or DNG.
#' @param year numeric. The desired year for Sentinel-2 cloudless mosaic
#' tiles. (This has to be specified when `datasource = "dentinel2"`)
#' @param floor logical. (only required for `get_bgvi`)
#' Whether to compute Building Green View Index (BGVI) for each floor level
#' based on estimated number of floors. Default is `FALSE`.
#' @param key character. (only required for `get_bgvi`)
#' API key of OpenTopography.
#'
#' @return
#' `get_bgvi` returns an `sf` object identical to input \code{x},
#' with additional columns for:
#' \itemize{
#'   \item \code{mean_gvi}: Mean Building Green View Index value (0 to 1) from selected height(s).
#'   \item \code{min_gvi}, \code{max_gvi}, \code{sd_gvi}: Minimum, maximum,
#'   and standard deviation of Green View Index (GVI) (if \code{floor = TRUE}).
#'   \item \code{estimated_floors}: Estimated number of floors based on building height
#'   (if \code{floor = TRUE}).
#'}
#'
#' @note
#' To request an OpenTopography API token, please visit:
#' [https://portal.opentopography.org/requestService?service=api](https://portal.opentopography.org/requestService?service=api)
#'
#' USGS 3DEP 1m/10m raster dataset is currently restricted to academic users.
#' Academic users can request access to these data via the OpenTopography portal.
#' Non-academic users can enquire about an enterprise API key by emailing info@opentopography.org.
#' See OpenTopography Terms of Use for more information on appropriate use of the API.
#'
#'
#' @examples
#' \donttest{
#' result <- gloBFPr::get_bgvi(globfp_example[c(1:3),],
#'                             key = "YOUR_opentopography_API_KEY")
#' }
#'
#' @references
#' Qi, L., Hu, Y., Bu, R., Xiong, Z., Li, B., Zhang, C., ... & Li, C. (2024).
#' Spatial-temporal patterns and influencing factors of the Building Green View
#' Index: A new approach for quantifying 3D urban greenery visibility.
#' Sustainable Cities and Society, 111, 105518.
#'
#' @export
#' @rdname get_metrics

get_bgvi <- function(x = NULL,
                     datasource = NULL,
                     min_tree_height = 2,
                     zoom = 17,
                     radius = 800,
                     year = NULL,
                     floor = FALSE,
                     key = NULL) {
  if (inherits(x, 'NULL')) {
    cli::cli_alert_info("Please input building footprint polygon generated by `search_3dglobdf()`.")
    return(x)
  }
  if (inherits(key, 'NULL')) {
    stop("API key for OpenTopography is missing.")
  }

  # Store the original 'timeout' option and ensure it's reset upon function exit
  original_timeout <- getOption('timeout')
  on.exit(options(timeout = original_timeout), add = TRUE)
  options(timeout=9999)

  old_opt <- getOption("future.globals.maxSize")
  on.exit(options(future.globals.maxSize = old_opt), add = TRUE)
  options(future.globals.maxSize = 3 * 1024^3)

  terra::terraOptions(progress=0)
  on.exit(terra::terraOptions(progress=3), add = TRUE)

  workers <- as.numeric(future::availableCores())
  # Set future plan depending on OS
  os <- Sys.info()[["sysname"]]
  if (os == "Windows" || isFALSE(parallelly::supportsMulticore())) {
    future::plan(future::multisession, workers = workers - 1)
  } else {
    future::plan(future::multicore, workers = workers - 1)
  }
  on.exit(future::plan(future::sequential), add = TRUE)

  start_time <- Sys.time()

  bbox <- get_bbox(x)
  utm_crs <- get_utm_crs(bbox)
  projected_poly <- sf::st_transform(x, utm_crs)
  bbox_vector <- bbox_poly_to_list(bbox)

  # download chm and dem
  cli::cli_alert_info('Start downloading canopy height and DEM ...')
  chm_layers <- suppressMessages(get_chm(bbox_vector, min_tree_height))
  dem <- get_dem(bbox_vector, key)

  # cli::cli_alert_info('Start calculating Green View Idex (GVI) ...')
  chm_n_dem <- unify_layers(bbox, chm_layers[[1]], dem)
  chm <- chm_n_dem[[1]]
  binary_chm <- chm_layers[[2]]
  dem <- chm_n_dem[[2]]
  dsm <- chm + dem

  projected_poly$g_area <- as.numeric(sf::st_area(projected_poly))

  if (isTRUE(floor)) {
    projected_poly$estimated_floors <- round(projected_poly$Height / 3)
    projected_poly$estimated_floors <- base::ifelse(
      projected_poly$g_area < 30 | projected_poly$Height < 6,
      1,
      projected_poly$estimated_floors
    )
    projected_poly$min_gvi <- 0
    projected_poly$max_gvi <- 0
    projected_poly$sd_gvi  <- 0
  }
  projected_poly$mean_gvi <- 0

  # --- Helper Function ---
  compute_gvi_per_building <- function(building,
                                       other_buildings,
                                       dsm_path,
                                       binary_chm_path,
                                       bbox,
                                       radius,
                                       floor) {
    # Read raster files inside each worker
    dsm <- terra::rast(dsm_path)
    binary_chm <- terra::rast(binary_chm_path)

    # Compute centroid
    p <- suppressWarnings(sf::st_centroid(building$geometry))
    p <- as.vector(sf::st_coordinates(p))

    # Create building height surface
    bh <- rasterize_height(other_buildings, bbox, terra::res(dsm)[1])
    chm_n_bh <- unify_layers(bbox, dsm - terra::rast(binary_chm_path), bh)  # use dsm - binary_chm as CHM input
    bh <- chm_n_bh[[2]]
    dsm_ <- bh + dsm

    if (isTRUE(floor)) {
      GVIs <- numeric(building$estimated_floors)
      for (h in seq_len(building$estimated_floors)) {
        height <- 1.7 + (h - 1) * 3
        GVIs[h] <- get_gvi(dsm_, p, height, radius, building, binary_chm)
      }
      return(list(
        mean = mean(GVIs),
        min = min(GVIs),
        max = max(GVIs),
        sd = if (length(GVIs) > 1) stats::sd(GVIs) else NA_real_
      ))
    } else {
      height_bottom <- 1.7
      if (building$Height < 6) {
        mean_gvi <- get_gvi(dsm_, p, height_bottom, radius, building, binary_chm)
      } else {
        height_top <- 1.7 + building$Height - 3
        gvi_top <- get_gvi(dsm_, p, height_top, radius, building, binary_chm)
        gvi_bottom <- get_gvi(dsm_, p, height_bottom, radius, building, binary_chm)
        mean_gvi <- mean(c(gvi_top, gvi_bottom))
      }
      return(list(mean = mean_gvi, min = NA_real_, max = NA_real_, sd = NA_real_))
    }
  }

  # --- Parallel Processing ---
  # cli::cli_alert_info('Preparing parallel processing ...')
  pb <- utils::txtProgressBar(min = 0, max = nrow(projected_poly), style = 3)
  building_list <- lapply(seq_len(nrow(projected_poly)), function(i) {
    utils::setTxtProgressBar(pb, i)
    list(
      building = projected_poly[i, ],
      other_buildings = projected_poly[-i, ]
    )
  })

  # Save raster layers to disk to avoid pointer serialization issues
  dsm_path <- tempfile(fileext = ".tif")
  binary_chm_path <- tempfile(fileext = ".tif")
  terra::writeRaster(dsm, dsm_path, overwrite = TRUE)
  terra::writeRaster(binary_chm, binary_chm_path, overwrite = TRUE)
  on.exit(unlink(c(dsm_path, binary_chm_path)), add = TRUE)

  gvi_results <- furrr::future_map(
    building_list,
    function(b) compute_gvi_per_building(
      building = b$building,
      other_buildings = b$other_buildings,
      dsm_path = dsm_path,
      binary_chm_path = binary_chm_path,
      bbox = bbox,
      radius = radius,
      floor = floor
    ),
    .options = furrr::furrr_options(seed = TRUE),
    .progress = TRUE
  )

  projected_poly$mean_gvi <- vapply(gvi_results, function(x) x$mean, numeric(1))
  if (isTRUE(floor)) {
    projected_poly$min_gvi <- vapply(gvi_results, function(x) x$min, numeric(1))
    projected_poly$max_gvi <- vapply(gvi_results, function(x) x$max, numeric(1))
    projected_poly$sd_gvi  <- vapply(gvi_results, function(x) x$sd, numeric(1))
  }
  # cli::cli_alert_success('Finished calculating GVIs')

  end_time <- Sys.time()
  process_time <- as.numeric(difftime(end_time, start_time, units = "secs"))
  time_taken(process_time)

  return(projected_poly)
}

#' @description
#' `get_dng`: Calculate the distance to the nearest greenspace (DNG) patch
#' for each building volume
#' @param min_area numeric. (only required for `get_dng`) The minimum area
#' (the unit is defined by `unit`) of greenspace patches within the proximity of
#' a building.
#' For example, when `min_area = 500`, any greenspace patches with area less than
#' 500 square meter will be excluded.
#' @param unit character. (only required for `get_dng`) The unit for
#' `min_area`: 'm2','ha', and 'km2'.
#'
#' @return
#' `get_dng` returns an `sf` object identical to input \code{x},
#' with an additional column:
#' \code{dng}: Distance to nearest green space (tree canopy pixe)l (in meters).
#'
#' @examples
#' result <- gloBFPr::get_dng(#globfp_example[c(1:3),],
#'                                  datasource = "metachm",
#'                                  unit = "m2")
#'

get_dng <- function(x = NULL,
                     datasource = NULL,
                     min_tree_height = 2,
                     zoom = 17,
                     radius = 800,
                     min_area = 500,
                     unit = c('m2','ha','km2'),
                     year = NULL) {
  if (inherits(x, 'NULL')) {
    cli::cli_alert_info("Please input building footprint polygon.")
    return(x)
  }

  bbox <- get_bbox(x)
  utm_crs <- get_utm_crs(bbox)
  projected_poly <- sf::st_transform(x, utm_crs)
  projected_poly$dng <- 0

  for (i in seq_len(nrow(projected_poly))) {
    poly_ <- projected_poly[i, ]$geometry
    buffer_ <- get_buffer(x = poly_, radius = radius)
    gs <- get_greenspace(buffer_$bbox, buffer_$buffer, datasource, zoom, year)
    gs <- filter_patch_area(gs, min_area, unit = unit, directions = 8)
    green_points <- terra::as.points(gs, na.rm = TRUE)
    green_points_sf <- sf::st_as_sf(green_points)
    nearest_index <- sf::st_nearest_feature(buffer_$centroid, green_points_sf)
    nearest_point <- green_points_sf[nearest_index, ]
    distance <- sf::st_distance(buffer_$centroid, nearest_point)
    projected_poly$dng[i] <- distance
  }
  return(projected_poly)
}

