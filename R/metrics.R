#' @description
#' `get_green_acc`: Calculate visual and distance accessibility of greenery for each building volume
#' @param min_tree_height numeric. (only required for `get_green_acc`)
#' Minimum height threshold (in meters) to classify vegetation as trees in the CHM.
#' Default is 2.
#' @param floor logical. (only required for `get_green_acc`) Whether to compute
#' Green View Index (GVI) for each floor level based on estimated number of floors.
#' Default is `FALSE`.
#' @param key character. (only required for `get_green_acc`) API key of OpenTopography.
#'
#' @return
#' `get_neighbors` returns an `sf` object identical to input \code{x},
#' with additional columns for:
#' \itemize{
#'   \item \code{dng}: Distance to nearest green space (tree canopy pixe)l (in meters).
#'   \item \code{mean_gvi}: Mean Green View Index value (0 to 1) from selected height(s).
#'   \item \code{min_gvi}, \code{max_gvi}, \code{sd_gvi}: Minimum, maximum,
#'   and standard deviation of Green View Index (GVI) (if \code{floor = TRUE}).
#'   \item \code{estimated_floors}: Estimated number of floors based on building height
#'   (if \code{floor = TRUE}).
#'}
#'
#' @note
#' To request an OpenTopography API token, please visit: [https://portal.opentopography.org/requestService?service=api](https://portal.opentopography.org/requestService?service=api)
#'
#' USGS 3DEP 1m/10m raster dataset is currently restricted to academic users.
#' Academic users can request access to these data via the OpenTopography portal.
#' Non-academic users can enquire about an enterprise API key by emailing info@opentopography.org.
#' See OpenTopography Terms of Use for more information on appropriate use of the API.
#'
#'
#' @examples
#' \donttest{
#' result <- gloBFPr::get_green_acc(globfp_example[c(1:3),], key = "YOUR_opentopography_API_KEY")
#' }
#'
#' @export
#' @rdname get_metrics

get_green_acc <- function(x = NULL,
                          min_tree_height = 2,
                          radius = 800,
                          floor = FALSE,
                          key = NULL) {
  if (inherits(x, 'NULL')) {
    cli::cli_alert_info("Please input building footprint polygon generated by `search_3dglobdf()`.")
    return(x)
  }
  if (inherits(key, 'NULL')) {
    stop("API key for OpenTopography is missing.")
  }

  # Store the original 'timeout' option and ensure it's reset upon function exit
  original_timeout <- getOption('timeout')
  on.exit(options(timeout = original_timeout), add = TRUE)
  options(timeout=9999)

  old_opt <- getOption("future.globals.maxSize")
  on.exit(options(future.globals.maxSize = old_opt), add = TRUE)
  options(future.globals.maxSize = 3 * 1024^3)

  workers <- as.numeric(future::availableCores())
  # Set future plan depending on OS
  os <- Sys.info()[["sysname"]]
  if (os == "Windows" || isFALSE(parallelly::supportsMulticore())) {
    future::plan(future::multisession, workers = workers - 1)
  } else {
    future::plan(future::multicore, workers = workers - 1)
  }
  on.exit(future::plan(future::sequential), add = TRUE)

  start_time <- Sys.time()

  projected_poly <- x
  bbox <- get_bbox(x)
  bbox_vector <- bbox_poly_to_list(bbox)

  # download chm and dem
  cli::cli_alert_info('Start downloading canopy height and DEM ...')
  chm_layers <- suppressMessages(get_chm(bbox_vector, min_tree_height))
  dem <- get_dem(bbox_vector, key)
  cli::cli_alert_success('Finished downloading and loading')

  # --- Distance to Nearest Green Space (DNG) ---
  cli::cli_alert_info('Start calculating Distance to Nearest Green Space (DNG) ...')
  isolated_chm <- terra::ifel(chm_layers[[2]] == 0, NA, 1)
  green_points <- terra::as.points(isolated_chm, na.rm = TRUE)
  green_points_sf <- sf::st_as_sf(green_points)
  building_centroids <- suppressWarnings(sf::st_centroid(x))
  green_points_sf <- sf::st_transform(green_points_sf, crs = sf::st_crs(x))
  nearest_index <- sf::st_nearest_feature(building_centroids, green_points_sf)
  nearest_points <- green_points_sf[nearest_index, ]
  distances <- sf::st_distance(building_centroids, nearest_points, by_element = TRUE)
  projected_poly$dng <- as.numeric(distances)
  cli::cli_alert_success('Finished calculating DNG')

  # --- GVI Setup ---
  cli::cli_alert_info('Start calculating Green View Idex (GVI) ...')
  chm_n_dem <- unify_layers(bbox, chm_layers[[1]], dem)
  chm <- chm_n_dem[[1]]
  binary_chm <- chm_layers[[2]]
  dem <- chm_n_dem[[2]]
  dsm <- chm + dem

  projected_poly$g_area <- as.numeric(sf::st_area(projected_poly))

  if (isTRUE(floor)) {
    projected_poly$estimated_floors <- round(projected_poly$Height / 3)
    projected_poly$estimated_floors <- base::ifelse(
      projected_poly$g_area < 30 | projected_poly$Height < 6,
      1,
      projected_poly$estimated_floors
    )
    projected_poly$min_gvi <- 0
    projected_poly$max_gvi <- 0
    projected_poly$sd_gvi  <- 0
  }
  projected_poly$mean_gvi <- 0

  # --- Helper Function ---
  compute_gvi_per_building <- function(building,
                                       other_buildings,
                                       dsm_path,
                                       binary_chm_path,
                                       bbox,
                                       radius,
                                       floor) {
    # Read raster files inside each worker
    dsm <- terra::rast(dsm_path)
    binary_chm <- terra::rast(binary_chm_path)

    # Compute centroid
    p <- suppressWarnings(sf::st_centroid(building$geometry))
    p <- as.vector(sf::st_coordinates(p))

    # Create building height surface
    bh <- rasterize_height(other_buildings, bbox, terra::res(dsm)[1])
    chm_n_bh <- unify_layers(bbox, dsm - terra::rast(binary_chm_path), bh)  # use dsm - binary_chm as CHM input
    bh <- chm_n_bh[[2]]
    dsm_ <- bh + dsm

    if (isTRUE(floor)) {
      GVIs <- numeric(building$estimated_floors)
      for (h in seq_len(building$estimated_floors)) {
        height <- 1.7 + (h - 1) * 3
        GVIs[h] <- get_gvi(dsm_, p, height, radius, building, binary_chm)
      }
      return(list(
        mean = mean(GVIs),
        min = min(GVIs),
        max = max(GVIs),
        sd = if (length(GVIs) > 1) stats::sd(GVIs) else NA_real_
      ))
    } else {
      height_bottom <- 1.7
      if (building$Height < 6) {
        mean_gvi <- get_gvi(dsm_, p, height_bottom, radius, building, binary_chm)
      } else {
        height_top <- 1.7 + building$Height - 3
        gvi_top <- get_gvi(dsm_, p, height_top, radius, building, binary_chm)
        gvi_bottom <- get_gvi(dsm_, p, height_bottom, radius, building, binary_chm)
        mean_gvi <- mean(c(gvi_top, gvi_bottom))
      }
      return(list(mean = mean_gvi, min = NA_real_, max = NA_real_, sd = NA_real_))
    }
  }

  # --- Parallel Processing ---
  cli::cli_alert_info('Preparing parallel processing ...')
  pb <- utils::txtProgressBar(min = 0, max = nrow(projected_poly), style = 3)
  building_list <- lapply(seq_len(nrow(projected_poly)), function(i) {
    utils::setTxtProgressBar(pb, i)
    list(
      building = projected_poly[i, ],
      other_buildings = projected_poly[-i, ]
    )
  })

  # Save raster layers to disk to avoid pointer serialization issues
  dsm_path <- tempfile(fileext = ".tif")
  binary_chm_path <- tempfile(fileext = ".tif")
  terra::writeRaster(dsm, dsm_path, overwrite = TRUE)
  terra::writeRaster(binary_chm, binary_chm_path, overwrite = TRUE)
  on.exit(unlink(c(dsm_path, binary_chm_path)), add = TRUE)

  cli::cli_alert_info('Parallel Processing ...')
  gvi_results <- furrr::future_map(
    building_list,
    function(b) compute_gvi_per_building(
      building = b$building,
      other_buildings = b$other_buildings,
      dsm_path = dsm_path,
      binary_chm_path = binary_chm_path,
      bbox = bbox,
      radius = radius,
      floor = floor
    ),
    .options = furrr::furrr_options(seed = TRUE),
    .progress = TRUE
  )

  projected_poly$mean_gvi <- vapply(gvi_results, function(x) x$mean, numeric(1))
  if (isTRUE(floor)) {
    projected_poly$min_gvi <- vapply(gvi_results, function(x) x$min, numeric(1))
    projected_poly$max_gvi <- vapply(gvi_results, function(x) x$max, numeric(1))
    projected_poly$sd_gvi  <- vapply(gvi_results, function(x) x$sd, numeric(1))
  }
  cli::cli_alert_success('Finished calculating GVIs')

  end_time <- Sys.time()
  process_time <- as.numeric(difftime(end_time, start_time, units = "secs"))
  if (process_time >= 60) {
    cli::cli_alert_success(paste0("Completed. Time taken: ", round(process_time / 60), " minutes."))
  } else {
    cli::cli_alert_success(paste0("Completed. Time taken: ", round(process_time), " seconds."))
  }

  return(projected_poly)
}



